def test_revision_invariants(retrieval_result):
    """Test that question_type and knowledge_point_ids are preserved after revision."""
    req = GenerateRequest(
        mode="fresh",
        question_types=["single_choice"],
        total_questions=3,
        revision_intensity="light",
        free_text="测试不变量",
    )
    paper = build_paper(req, retrieval_result)

    original_kps = [ri.question.knowledge_point_ids for ri in retrieval_result.items]
    original_qts = [ri.question.question_type for ri in retrieval_result.items]

    for i, item in enumerate(paper.items):
        assert item.question.question_type == original_qts[i]
        assert set(item.question.knowledge_point_ids) == set(original_kps[i])


def test_answer_format_validation(retrieval_result):
    """Test that answer format is correct for single choice questions."""
    req = GenerateRequest(
        mode="fresh",
        question_types=["single_choice"],
        total_questions=3,
        revision_intensity="original",
        free_text="测试答案格式",
    )
    paper = build_paper(req, retrieval_result)

    for item in paper.items:
        assert item.question.answer in {"A", "B", "C", "D"}
        assert item.question.options is not None
        assert len(item.question.options) == 4
        labels = {opt.label for opt in item.question.options}
        assert labels == {"A", "B", "C", "D"}